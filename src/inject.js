/* PostHog Blocker, page layer. Runs in the page's MAIN world at document_start, before any page script.
   1. window.posthog is a locked, inert stub with __SV set, so the official snippet and loaders that check
      __SV never add the SDK <script>; calls on it do nothing and feature flags read as off.
   2. fetch, XMLHttpRequest and sendBeacon drop PostHog requests and answer them with a fake 200, so a bundled
      or inlined SDK sending through any first-party proxy path stays quiet and doesn't retry.
   URL patterns mirror rules/posthog.json (test/patterns.test.mjs checks both against the same fixtures). */
(() => {
  'use strict'

  const URL_PATTERNS = [
    ['sdk', /\/(?:static|array)\/(?:[0-9]+\.[0-9]+\.[0-9]+\/)?(?:array(?:\.full)?(?:\.no-external)?|recorder(?:-v2)?|lazy-recorder|posthog-recorder)(?:\.min)?\.js(?:[?#]|$)/i],
    ['sdk', /\/posthog(?:[._-][A-Za-z0-9._-]*)?\.m?js(?:[?#]|$)/i],
    ['sdk', /\/posthog-js(?:@[^/]*)?\//i],
    ['sdk', /\/vendor\/posthog\//i],
    ['token', /[/=]phc_[A-Za-z0-9]{30,}/],
    ['ingest', /^https?:\/\/[^/]+\/(?:[^?#]*\/)?(?:e|s|i\/v0\/e|i\/v1\/(?:logs|metrics)|batch|engage|capture|track)\/?\?(?:[^#]*&)?(?:compression=(?:gzip-js|base64)|_=[0-9]{13}|sent_at=[0-9]|ver=1\.[0-9]|retry_count=[0-9]|ip=[01])/i],
    ['flags', /^https?:\/\/[^/]+\/(?:[^?#]*\/)?(?:flags|decide)\/?\?(?:[^#]*&)?v=[0-9]/i],
    ['ingest', /[?&]compression=gzip-js(?:&|#|$)/i],
    ['proxy', /\/(?:ingest|ph|_ph|phog|posthog|ph-proxy|phproxy)\/(?:e|s|i\/v0\/e|i\/v1\/[a-z]+|flags|decide|batch|engage|capture|static|array)(?:\/|\?|$)/i]
  ]
  const POSTHOG_HOST = /(?:^|\.)(?:i\.posthog\.com|app\.posthog\.com|us\.posthog\.com|eu\.posthog\.com)$/i
  const OWN_SITE = /(?:^|\.)(?:ciunkos\.com|przemyslawzalewski\.com|przemyslawzalewski\.pl)$/i
  const OWN_PROXY = /^\/(?:[^?#]*\/)?ph\//
  /* A PostHog payload: the project token as the "token" / "api_key" field, or anywhere as a phc_ key. */
  const BODY_PATTERN = /["']?(?:token|api_key)["']?\s*[:=]\s*["']?phc_[A-Za-z0-9]{20,}|phc_[A-Za-z0-9]{40,}/

  const matchUrl = raw => {
    let url
    try {
      url = new URL(String(raw), location.href)
    } catch (error) {
      return null
    }
    if (!/^https?:$/.test(url.protocol)) return null
    if (POSTHOG_HOST.test(url.hostname)) return 'host'
    if (OWN_SITE.test(url.hostname) && OWN_PROXY.test(url.pathname)) return 'proxy'
    const href = url.href
    for (const [reason, pattern] of URL_PATTERNS) {
      if (pattern.test(href)) return reason
    }
    return null
  }

  const MAX_BODY = 1 << 20
  const decoder = new TextDecoder()
  const textOf = body => {
    if (body == null) return null
    if (typeof body === 'string') return body
    if (body instanceof URLSearchParams) return body.toString()
    if (typeof FormData !== 'undefined' && body instanceof FormData) {
      const parts = []
      body.forEach((value, key) => parts.push(`${key}=${typeof value === 'string' ? value : ''}`))
      return parts.join('&')
    }
    try {
      if (body instanceof ArrayBuffer) return body.byteLength <= MAX_BODY ? decoder.decode(body) : null
      if (ArrayBuffer.isView(body)) return body.byteLength <= MAX_BODY ? decoder.decode(body) : null
    } catch (error) {
      return null
    }
    return null
  }
  const matchText = text => (text && text.length <= MAX_BODY * 2 && BODY_PATTERN.test(text) ? 'payload' : null)
  const matchBody = body => matchText(textOf(body))

  /* SRI hash prefixes of known PostHog SDK files (src/sri-hashes.js, generated by scripts/sri-hashes.mjs) */
  const SRI_KEY = Symbol.for('posthog-blocker.sri')
  const sriList = globalThis[SRI_KEY]
  try {
    delete globalThis[SRI_KEY]
  } catch (error) {
    // not ours to delete
  }
  const SRI = new Set(typeof sriList === 'string' ? sriList.split(' ') : [])
  const matchIntegrity = value => {
    for (const token of String(value || '').trim().split(/\s+/)) {
      const m = /^(sha256|sha384|sha512)-([A-Za-z0-9+/=_-]{12})/.exec(token)
      if (m && SRI.has(`${m[1]}-${m[2]}`)) return 'sri'
    }
    return null
  }

  /* test/patterns.test.mjs evaluates this file in a sandbox that defines __PHB_EXPORT__; pages never get here first. */
  if (typeof __PHB_EXPORT__ === 'function') {
    __PHB_EXPORT__({ matchUrl, matchBody, matchText, matchIntegrity, sriSize: SRI.size })
    return
  }

  const report = (url, reason, via) => {
    try {
      document.dispatchEvent(
        new CustomEvent('posthog-blocker:blocked', { detail: JSON.stringify({ url: String(url).slice(0, 300), reason, via }) })
      )
    } catch (error) {
      // reporting must not break the page
    }
  }

  const fakeBody = url =>
    /\/(?:flags|decide)\/?(?:\?|$)/.test(String(url))
      ? '{"featureFlags":{},"featureFlagPayloads":{},"flags":{},"errorsWhileComputingFlags":false,"quotaLimited":[]}'
      : '{}'

  /* 1. The stub */
  const noop = new Proxy(function () {}, {
    get: (target, key) => (key === 'then' || typeof key === 'symbol' ? undefined : noop),
    apply: () => undefined
  })
  const later = fn => {
    if (typeof fn === 'function') setTimeout(() => { try { fn([], {}, { errorsLoading: false }) } catch (error) { /* page code */ } })
  }
  const unsubscribe = () => () => {}
  let stubUsed = false
  const used = method => {
    if (stubUsed) return
    stubUsed = true
    report(location.href, 'stub', `posthog.${method}`)
  }
  const known = {
    __SV: 1,
    __loaded: true,
    __blocked: true,
    _i: [],
    config: {},
    version: '0.0.0-blocked',
    init: () => { used('init'); return stub },
    push: () => { used('push') },
    capture: () => { used('capture') },
    has_opted_out_capturing: () => true,
    has_opted_in_capturing: () => false,
    is_capturing: () => false,
    isFeatureEnabled: () => false,
    getFeatureFlag: () => undefined,
    getFeatureFlagPayload: () => undefined,
    getFeatureFlagResult: () => undefined,
    getAllFlags: () => ({}),
    onFeatureFlags: fn => { later(fn); return () => {} },
    getSurveys: fn => { later(fn); },
    getActiveMatchingSurveys: fn => { later(fn); },
    getEarlyAccessFeatures: fn => { later(fn); },
    get_distinct_id: () => '',
    getDistinctId: () => '',
    get_session_id: () => '',
    getSessionId: () => '',
    get_property: () => undefined,
    getProperty: () => undefined,
    sessionRecordingStarted: () => false,
    on: unsubscribe,
    onSessionId: unsubscribe,
    onSurveysLoaded: unsubscribe,
    featureFlags: new Proxy({ getFlags: () => [], getFlagVariants: () => ({}), getFlagPayloads: () => ({}) }, {
      get: (target, key) => (key in target ? target[key] : noop)
    }),
    toString: () => 'posthog (blocked by PostHog Blocker)'
  }
  const stub = new Proxy(known, {
    get: (target, key) => (key in target ? target[key] : typeof key === 'symbol' ? undefined : noop),
    set: () => true,
    deleteProperty: () => true,
    defineProperty: () => true
  })
  try {
    Object.defineProperty(window, 'posthog', { configurable: false, enumerable: true, get: () => stub, set: () => { used('assign') } })
  } catch (error) {
    // already defined as non-configurable by someone else
  }

  /* 2. Scripts with the integrity hash of a known PostHog build, whatever their URL. A script whose type is not
        JavaScript is neither fetched nor run, as long as the type changes before the browser prepares it:
        - set from JS: the integrity setter / setAttribute run before the element is inserted;
        - in the HTML: the parser runs a microtask checkpoint before preparing a script, so the observer is first. */
  const defused = new WeakSet()
  const nativeSetAttribute = Element.prototype.setAttribute
  const defuse = (script, value, via) => {
    if (defused.has(script) || !matchIntegrity(value)) return
    defused.add(script)
    nativeSetAttribute.call(script, 'type', 'text/plain')
    nativeSetAttribute.call(script, 'data-posthog-blocker', 'sri')
    report(script.getAttribute('src') || location.href, 'sri', via)
    // loaders wait for load or error; error makes them give up
    setTimeout(() => script.dispatchEvent(new Event('error')))
  }
  if (SRI.size && typeof HTMLScriptElement === 'function') {
    const descriptor = Object.getOwnPropertyDescriptor(HTMLScriptElement.prototype, 'integrity')
    if (descriptor && descriptor.set) {
      Object.defineProperty(HTMLScriptElement.prototype, 'integrity', {
        ...descriptor,
        set(value) {
          descriptor.set.call(this, value)
          defuse(this, value, 'script.integrity')
        }
      })
    }
    Element.prototype.setAttribute = function setAttribute(name, value) {
      const result = nativeSetAttribute.apply(this, arguments)
      if (this instanceof HTMLScriptElement && String(name).toLowerCase() === 'integrity') {
        defuse(this, value, 'setAttribute')
      }
      return result
    }
    new MutationObserver(records => {
      for (const record of records) {
        for (const node of record.addedNodes) {
          if (node instanceof HTMLScriptElement && node.hasAttribute('integrity')) {
            defuse(node, node.getAttribute('integrity'), 'html')
          }
        }
      }
    }).observe(document, { childList: true, subtree: true })
  }

  /* 3. Network */
  const nativeFetch = window.fetch
  if (typeof nativeFetch === 'function') {
    const fake = url => new Response(fakeBody(url), { status: 200, headers: { 'Content-Type': 'application/json' } })
    const wrapped = function fetch(input, init) {
      let url
      let body
      let method = 'GET'
      try {
        url = input instanceof Request ? input.url : String(input)
        method = String((init && init.method) || (input instanceof Request ? input.method : 'GET')).toUpperCase()
        body = init && init.body
        const reason = matchUrl(url) || matchBody(body)
        if (reason) {
          report(url, reason, 'fetch')
          return Promise.resolve(fake(url))
        }
      } catch (error) {
        return nativeFetch.apply(this, arguments)
      }
      // a Blob or Request body needs an async read; only small POST-like bodies are worth it
      const blob = typeof Blob !== 'undefined' && body instanceof Blob ? body : null
      if (method !== 'GET' && method !== 'HEAD' && ((blob && blob.size <= MAX_BODY) || (!body && input instanceof Request))) {
        const args = arguments
        const read = blob ? blob.text() : input.clone().text()
        return read.then(
          text => {
            const reason = matchText(text)
            if (reason) {
              report(url, reason, 'fetch')
              return fake(url)
            }
            return nativeFetch.apply(this, args)
          },
          () => nativeFetch.apply(this, args)
        )
      }
      return nativeFetch.apply(this, arguments)
    }
    window.fetch = wrapped
  }

  const XHR = window.XMLHttpRequest
  if (typeof XHR === 'function') {
    const urls = new WeakMap()
    const { open, send } = XHR.prototype
    XHR.prototype.open = function (method, url) {
      urls.set(this, url)
      return open.apply(this, arguments)
    }
    XHR.prototype.send = function (body) {
      let reason = null
      const url = urls.get(this)
      try {
        reason = matchUrl(url) || matchBody(body)
      } catch (error) {
        reason = null
      }
      if (!reason) return send.apply(this, arguments)
      report(url, reason, 'xhr')
      const xhr = this
      const text = fakeBody(url)
      const define = (key, value) => Object.defineProperty(xhr, key, { configurable: true, get: () => value })
      setTimeout(() => {
        define('readyState', 4)
        define('status', 200)
        define('statusText', 'OK')
        define('responseText', text)
        define('response', xhr.responseType === 'json' ? JSON.parse(text) : text)
        define('responseURL', String(url))
        for (const type of ['readystatechange', 'load', 'loadend']) {
          try {
            xhr.dispatchEvent(new Event(type))
          } catch (error) {
            // page handler
          }
        }
      })
      return undefined
    }
  }

  const beacon = navigator.sendBeacon
  if (typeof beacon === 'function') {
    navigator.sendBeacon = function sendBeacon(url, data) {
      try {
        const reason = matchUrl(url) || matchBody(data)
        if (reason) {
          report(url, reason, 'beacon')
          return true
        }
      } catch (error) {
        // fall through to the real beacon
      }
      return beacon.apply(this, arguments)
    }
  }
})()
